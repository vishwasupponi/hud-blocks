import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the github repository.
*/
`;

const prod = process.argv[2] === "production";

const builtins = [
    "assert", "buffer", "child_process", "cluster", "crypto", "dgram", "dns",
    "domain", "events", "fs", "http", "https", "net", "os", "path", "punycode",
    "querystring", "readline", "stream", "string_decoder", "timers", "tls",
    "tty", "url", "util", "v8", "vm", "zlib"
];

const buildOptions = {
    banner: { js: banner },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtins,
        ...builtins.map(b => `node:${b}`)
    ],
    format: "cjs",
    target: "es2020",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "main.js"
};

function syncReleaseFolder() {
    const releaseDir = path.resolve("hud-blocks");
    if (fs.existsSync(releaseDir)) {
        if (fs.existsSync("main.js")) {
            fs.copyFileSync("main.js", path.join(releaseDir, "main.js"));
        }
        if (fs.existsSync("manifest.json")) {
            fs.copyFileSync("manifest.json", path.join(releaseDir, "manifest.json"));
        }
        if (fs.existsSync("styles.css")) {
            fs.copyFileSync("styles.css", path.join(releaseDir, "styles.css"));
        }
    }
}

if (prod) {
    await esbuild.build(buildOptions);
    syncReleaseFolder();
    process.exit(0);
} else {
    const ctx = await esbuild.context(buildOptions);
    await ctx.rebuild();
    syncReleaseFolder();
    await ctx.dispose();
}
